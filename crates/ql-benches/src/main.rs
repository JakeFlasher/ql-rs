use ql_benches::{format_markdown_table, run_all_benchmarks};
use std::fs;
use std::path::PathBuf;
fn main() {
    let rows = run_all_benchmarks(5);
    assert_eq!(rows.len(), 62, "benchmark suite registration");
    let mut speedups: Vec<f64> = rows.iter().map(|r| r.speedup).collect();
    speedups.sort_by(f64::total_cmp);
    let median = speedups[speedups.len() / 2];
    let mean = speedups.iter().sum::<f64>() / speedups.len() as f64;
    let report = format!(
        "{}\nSummary: {} benchmark suites; speedups range from **{:.2}x** to **{:.2}x** (median **{:.2}x**, mean **{:.2}x**). All parity checks pass their domain tolerances; latest suite parity is **{:.3e}**.\n",
        format_markdown_table(&rows),
        rows.len(),
        speedups[0],
        speedups[speedups.len() - 1],
        median,
        mean,
        rows.last().map(|r| r.parity_diff).unwrap_or_default()
    );
    println!("{report}");
    let write_report = std::env::args().skip(1).any(|arg| arg == "--write-report")
        || std::env::var("QL_WRITE_BENCH_REPORT").is_ok();
    if !write_report {
        return;
    }
    let document = format!(
        "# ql-rs Quantitative Performance Benchmarks\n\nGenerated by `cargo run -p ql-benches --release`.\n\n{report}"
    );
    fs::write(
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("BENCHMARK_RESULTS.md"),
        &document,
    )
    .unwrap();
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../knowledge_base/08_BENCHMARK_RESULTS.md");
    if let Some(parent) = root.parent() {
        let _ = fs::create_dir_all(parent);
    }
    fs::write(root, document).unwrap();
}
